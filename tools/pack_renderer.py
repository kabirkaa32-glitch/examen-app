"""Embed renderer/ into a generated Python module (_renderer_pack.py).

PyInstaller then compiles it INTO the EXE, so no editable index.html
remains on disk after installation. Run before PyInstaller.
"""
import base64, json, zlib, hashlib
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = root / "renderer"
files = {
    p.relative_to(src).as_posix(): base64.b64encode(p.read_bytes()).decode()
    for p in sorted(src.rglob("*")) if p.is_file()
}
if "index.html" not in files or "version.json" not in files:
    raise SystemExit("renderer/ must contain index.html and version.json")
version = json.loads(base64.b64decode(files["version.json"]))["version"]
payload = json.dumps({"version": version, "files": files}, separators=(",", ":")).encode()
blob = base64.b64encode(zlib.compress(payload, 9)).decode()
digest = hashlib.sha256(payload).hexdigest()
lines = [blob[i:i + 100] for i in range(0, len(blob), 100)]
out = "# AUTO-GENERATED by tools/pack_renderer.py - do not edit or commit\n"
out += f'DIGEST = "{digest}"\nBLOB = (\n' + "\n".join(f'    "{l}"' for l in lines) + "\n)\n"
(root / "_renderer_pack.py").write_text(out, encoding="utf-8")
print(f"Packed {len(files)} files, version {version}, {len(blob)//1024} KB")
